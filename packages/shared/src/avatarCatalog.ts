export type PresetAvatar = (typeof PRESET_AVATARS)[number];
export type PresetAvatarId = PresetAvatar["id"];

const byId = new Map<string, PresetAvatar>(PRESET_AVATARS.map((avatar) => [avatar.id, avatar]));

/** Values written by the first release of the old color-avatar picker. */
export const LEGACY_PRESET_COLORS = [
  "#0FA6A6",
  "#FF6B6B",
  "#4ECDC4",
  "#45B7D1",
  "#96CEB4",
  "#FFEAA7",
] as const;

export function getPresetAvatar(id: string | null | undefined): PresetAvatar | null {
  return id ? byId.get(id) ?? null : null;
}

export function isPresetAvatarId(id: string | null | undefined): id is PresetAvatarId {
  return !!getPresetAvatar(id);
}

export function presetAvatarValue(id: PresetAvatarId): `preset:${PresetAvatarId}` {
  return `preset:${id}`;
}

/** Returns a new stable preset ID only; legacy color values deliberately stay legacy. */
export function parsePresetAvatarId(value: string | null | undefined): PresetAvatarId | null {
  if (!value?.startsWith("preset:")) return null;
  const id = value.slice("preset:".length);
  return isPresetAvatarId(id) ? id : null;
}

/**
 * Retains the prior `preset:#hex` presentation without mapping it to a new
 * character.  That prevents an existing person from ever receiving a different
 * avatar simply because this catalog was introduced.
 */
export function parseLegacyPresetColor(value: string | null | undefined): string | null {
  if (!value?.startsWith("preset:") || parsePresetAvatarId(value)) return null;
  return value.slice("preset:".length) || null;
}

export function parseTextAvatar(value: string | null | undefined): string | null {
  if (!value?.startsWith("text:")) return null;
  return value.slice("text:".length) || null;
}
